# ── small helpers ────────────────────────────────────────────────────────────────────────────
def env(name):
    value = os.environ.get(name)
    if not value:
        raise Blocked("missing_information", "environment variable %s is not set (it holds a personal detail or secret)" % name)
    return value


def domain_ok(url):
    host = (urlsplit(url).hostname or "").lower()
    return not ALLOWED_DOMAINS or any(host == d or host.endswith("." + d) for d in ALLOWED_DOMAINS)


def pace():
    wait = PACE_S - (time.time() - _last_load[0])
    if wait > 0:
        time.sleep(wait)
    _last_load[0] = time.time()


def snap(page, label):
    try:
        _shots[0] += 1
        path = OUT_DIR / "screenshots" / ("%02d_%s.png" % (_shots[0], re.sub(r"[^A-Za-z0-9_-]+", "-", label)[:40]))
        path.parent.mkdir(parents=True, exist_ok=True)
        page.screenshot(path=str(path))
    except PlaywrightError:
        pass


def settle(page, cap_ms=10000):
    for state, cap in (("domcontentloaded", cap_ms), ("networkidle", min(cap_ms, 6000))):
        try:
            page.wait_for_load_state(state, timeout=cap)
        except PlaywrightTimeout:
            pass
    page.wait_for_timeout(500)


def not_blocked(page):
    """Stop (exit code 2) on a CAPTCHA / bot wall instead of fighting it."""
    try:
        text = page.evaluate("() => document.body ? document.body.innerText : ''") or ""
        shown = page.locator("iframe[src*='recaptcha'], iframe[src*='hcaptcha'], iframe[src*='challenges.cloudflare.com'], "
                             ".g-recaptcha, .h-captcha, .cf-turnstile").first
        widget = shown.count() > 0 and shown.is_visible()
    except PlaywrightError:
        return
    if len(text) < 3000 and (BLOCK_TEXT.search((page.title() or "") + " " + text[:700]) or widget):
        raise Blocked("captcha", "a CAPTCHA / bot-check page appeared at %s - a person must continue" % page.url)


def goto(page, url):
    if not domain_ok(url):
        raise Blocked("domain_not_allowed", "%s is outside ALLOWED_DOMAINS %s" % (url, ALLOWED_DOMAINS))
    pace()
    page.goto(url, wait_until="domcontentloaded", timeout=NAV_TIMEOUT_MS)
    settle(page)
    not_blocked(page)
    dismiss_banners(page)


def dismiss_banners(page):
    """Cookie banners / pop-ups that cover the page: prefer 'reject' or 'close'."""
    for pattern in (r"^(reject|decline|deny|refuse)(\s+all)?$|necessary only|only necessary", r"^(close|dismiss|no thanks|not now|skip)$|^[x×✕]$"):
        try:
            dialog = page.locator("[role=dialog], [aria-modal=true], [id*=cookie i], [class*=cookie i], [class*=consent i], [id*=consent i]").first
            if dialog.count() and dialog.is_visible():
                button = dialog.get_by_role("button", name=re.compile(pattern, re.I)).first
                if button.count() and button.is_visible():
                    button.click(timeout=3000)
                    page.wait_for_timeout(400)
                    return
        except PlaywrightError:
            continue


def locators(page, candidates):
    for c in candidates:
        try:
            if "role" in c:
                yield page.get_by_role(c["role"], name=re.compile(re.escape(c["name"]), re.I))
            elif "label" in c:
                yield page.get_by_label(re.compile(re.escape(c["label"]), re.I))
            elif "placeholder" in c:
                yield page.get_by_placeholder(re.compile(re.escape(c["placeholder"]), re.I))
            elif "text" in c:
                yield page.get_by_text(re.compile(re.escape(c["text"]), re.I))
            elif "href" in c:
                yield page.locator("a[href='%s']" % c["href"].replace("'", ""))
            elif "css" in c:
                yield page.locator(c["css"])
        except PlaywrightError:
            continue


def find(page, label, candidates, timeout_ms=None):
    """First visible element among several ways of finding it (role+name, label, placeholder, text, href, CSS)."""
    deadline = time.time() + (timeout_ms or STEP_TIMEOUT_MS) / 1000.0
    while True:
        for loc in locators(page, candidates):
            try:
                if loc.count() and loc.first.is_visible():
                    return loc.first
            except PlaywrightError:
                continue
        if time.time() > deadline:
            raise StepFailed("could not find %r (tried %d way(s) of locating it)" % (label, len(candidates)))
        page.wait_for_timeout(300)


def guard(text):
    if text and FORBIDDEN_CLICK.search(text):
        raise Blocked("policy_denied", "refusing to press %r: it looks like a payment / final-order control" % text[:60])


def click(page, label, candidates):
    guard(label)
    loc = find(page, label, candidates)
    try:
        guard((loc.inner_text(timeout=1500) or loc.get_attribute("aria-label") or "")[:80])
    except PlaywrightError:
        pass
    loc.scroll_into_view_if_needed(timeout=4000)
    loc.click(timeout=STEP_TIMEOUT_MS)
    settle(page)
    not_blocked(page)


def fill(page, label, candidates, text, submit=False):
    loc = find(page, label, candidates)
    loc.click(timeout=STEP_TIMEOUT_MS)
    loc.fill(text, timeout=STEP_TIMEOUT_MS)
    if submit:
        pace()
        loc.press("Enter")
        settle(page)
        not_blocked(page)


def select_option(page, label, candidates, value):
    loc = find(page, label, candidates)
    try:
        loc.select_option(label=value, timeout=STEP_TIMEOUT_MS)
    except PlaywrightError:
        loc.select_option(value=value, timeout=STEP_TIMEOUT_MS)
    settle(page)


def step(page, name, action, retries=None, optional=False):
    """Run one stage action with retries, logging and a screenshot; ``optional`` steps may fail without ending the run."""
    attempts = (RETRIES if retries is None else retries) + 1
    started = time.time()
    for n in range(1, attempts + 1):
        try:
            log.info("%s%s", name, "" if n == 1 else " (attempt %d)" % n)
            action()
            RESULT["steps"].append({"name": name, "ok": True, "seconds": round(time.time() - started, 1)})
            snap(page, name)
            return True
        except Blocked:
            snap(page, "blocked-" + name)
            raise
        except (StepFailed, PlaywrightTimeout, PlaywrightError) as exc:
            if n < attempts:
                log.warning("%s failed (%s); retrying", name, str(exc).splitlines()[0][:120])
                page.wait_for_timeout(1000 * n)
                continue
            RESULT["steps"].append({"name": name, "ok": False, "error": str(exc).splitlines()[0][:200]})
            snap(page, "failed-" + name)
            if optional:
                log.warning("optional step %s skipped", name)
                return False
            raise StepFailed("%s: %s" % (name, str(exc).splitlines()[0][:200]))


