def _tokens(text):
    return [t for t in re.split(r"[^\w]+", (text or "").lower()) if t]


def card_score(card, query):
    q, title = _tokens(query), _tokens(card["title"] + " " + card.get("slug", ""))
    if not q or not title:
        return 0.0
    hit = sum(1 for t in q if t in title) / len(q)
    precision = len(set(q) & set(title)) / len(set(title))
    models = [t for t in q if any(ch.isdigit() for ch in t)]
    model_hit = (sum(1 for t in models if t in title) / len(models)) if models else 1.0
    return 0.5 * hit + 0.2 * precision + 0.2 * model_hit + (0.3 if title == q else 0.0)


def _same_word(a, b):
    return a == b or a + "s" == b or b + "s" == a or a + "es" == b or b + "es" == a


def card_covers(card, query):
    """Does the listing name every significant product word (a model number always)?"""
    q = [t for t in _tokens(query) if len(t) > 1 or t.isdigit()]
    title = set(_tokens(card["title"] + " " + card.get("slug", "")))
    if not q or not title:
        return False
    found = [any(_same_word(t, x) for x in title) for t in q]
    need = len(q) if len(q) <= 3 else -(-3 * len(q) // 4)
    return sum(found) >= need and all(f for t, f in zip(q, found) if any(ch.isdigit() for ch in t))


def pick_product(page, query, pick="best", strict=False):
    """Choose the listed product that best matches the search words (re-decided on every run).
    strict=True: the cards were not ranked by a site search (it was not allowed or not available), so only a card that names every
    product word is acceptable - a wrong product is never picked just because one word fits."""
    cards = page.evaluate(PRODUCT_CARDS_JS) or page.evaluate(PRODUCT_LINKS_JS)      # a catalogue without prices has link cards only
    if not cards:
        raise StepFailed("no product cards found on %s" % page.url)
    if strict:
        fit = [c for c in cards if card_covers(c, query)]
        if not fit:
            raise Blocked("no_match", "no product listed on %s names every word of %r (closest: %s)" % (
                page.url, query, "; ".join(repr(c["title"]) for c in sorted(cards, key=lambda c: -card_score(c, query))[:4])))
        cards = fit
    ranked = sorted(((card_score(c, query), i, c) for i, c in enumerate(cards)), key=lambda x: (-x[0], x[1]))
    score, _i, card = ranked[0]
    if pick == "first":
        card = sorted(ranked, key=lambda x: x[1])[0][2]
    if score < 0.3:
        raise Blocked("no_match", "no listed product matches %r (best: %r)" % (query, card["title"]))
    RESULT["data"]["chosen_product"] = {"title": card["title"], "price": card["price"], "url": card["url"], "match_score": round(score, 2)}
    log.info("chose %r (%s)", card["title"], card["price"])
    goto(page, card["url"])


def read_product(page):
    data = page.evaluate(PRODUCT_JS)
    RESULT["data"]["product"] = data
    log.info("product: %s | price: %s %s | %s", data.get("title"), data.get("price"), data.get("currency"), data.get("availability"))
    if not data.get("price"):
        raise StepFailed("no price found on %s" % page.url)


def payment_page_reached(page):
    """Check (never act): card fields or payment methods are visible. The run stops here on purpose."""
    cards = page.locator("input[autocomplete^='cc-'], input[name*='card' i], input[name*='cvv' i], input[name*='cvc' i]").count()
    methods = page.locator("input[type=radio][name*=pay i], [class*='payment-method' i], [data-payment-method]").count()
    heading = re.search(r"payment|pay with|billing", page.evaluate("() => (document.body ? document.body.innerText : '').slice(0, 4000)") or "", re.I)
    RESULT["data"]["payment_page"] = {"url": page.url, "card_fields": cards, "payment_methods": methods}
    if not (cards >= 2 or (methods >= 2 and heading)):
        raise StepFailed("the payment page was not reached (card fields=%d, methods=%d)" % (cards, methods))
    RESULT["payment_reached"] = True
    log.info("payment page reached at %s - stopping here: nothing is paid", page.url)


def extract_rows(page, pages=1, limit=None):
    rows, seen = [], set()
    for n in range(1, pages + 1):
        for c in page.evaluate(PRODUCT_CARDS_JS):
            if c["url"] not in seen:
                seen.add(c["url"])
                rows.append(dict(c, page=n))
        if limit and len(rows) >= limit or n == pages:
            break
        nxt = page.locator("a[rel~=next], a:has-text('Next'), button:has-text('Next'), button:has-text('Load more')").first
        if not nxt.count() or not nxt.is_visible():
            break
        nxt.click(timeout=STEP_TIMEOUT_MS)
        settle(page)
    RESULT["data"]["rows"] = rows[:limit] if limit else rows
    (OUT_DIR / "rows.json").write_text(json.dumps(RESULT["data"]["rows"], indent=2, ensure_ascii=False), encoding="utf-8")
    if not rows:
        raise StepFailed("no rows were collected")


def route_guard(route):
    request = route.request
    try:
        if request.resource_type == "document" and request.frame.parent_frame is None and not domain_ok(request.url):
            log.warning("blocked navigation outside ALLOWED_DOMAINS: %s", request.url)
            return route.fulfill(status=204)
    except PlaywrightError:
        pass
    return route.fallback()


# ── the recorded task, stage by stage ───────────────────────────────────────────────────────
def run(page):
    # ── Open the site ─────────────────────────────────────────────────────────
    step(page, 'Open the site', lambda: goto(page, START_URL))
    # ── Read product details and price ────────────────────────────────────────
    step(page, 'Read product details and price', lambda: read_product(page))
    # ── Select required options (size / colour / variant) ─────────────────────
    step(page, 'click White', lambda: click(page, 'White', [{'role': 'button', 'name': 'White'}, {'css': '#module_sku-select > div > div > div > div'}]), optional=True)


def main(argv=None):
    global START_URL, SEARCH_QUERY, HEADLESS
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="print the configuration and exit without opening a browser")
    parser.add_argument("--headless", action="store_true", help="run without a visible window")
    parser.add_argument("--url", help="start URL (default: %s)" % START_URL)
    parser.add_argument("--query", help="product words to search for (default: %r)" % SEARCH_QUERY)
    args = parser.parse_args(argv)
    START_URL = args.url or START_URL
    SEARCH_QUERY = args.query or SEARCH_QUERY
    HEADLESS = HEADLESS or args.headless
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    if not START_URL.startswith(("http://", "https://")) or not domain_ok(START_URL):
        print("configuration problem: START_URL must be an http(s) URL inside ALLOWED_DOMAINS", file=sys.stderr)
        return 3
    if args.dry_run:
        print(json.dumps({"start_url": START_URL, "query": SEARCH_QUERY, "headless": HEADLESS, "allowed_domains": ALLOWED_DOMAINS,
                          "stages": ['Open the site', 'Read product details and price', 'Select required options (size / colour / variant)'], "needs_environment": [], "payment": "never submitted"}, indent=2))
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    code = 1
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=HEADLESS, slow_mo=SLOW_MO_MS, args=BROWSER_ARGS)
        context = browser.new_context(viewport={"width": 1366, "height": 850}, storage_state=STORAGE_STATE if STORAGE_STATE and Path(STORAGE_STATE).is_file() else None)
        context.set_default_timeout(STEP_TIMEOUT_MS)
        context.route("**/*", route_guard)
        page = context.new_page()
        try:
            run(page)
            RESULT["status"], code = "success", 0
        except Blocked as exc:
            RESULT.update(status="blocked", blocker={"kind": exc.kind, "message": str(exc)})
            log.error("BLOCKED (%s): %s", exc.kind, exc)
            code = 2
        except (StepFailed, PlaywrightTimeout, PlaywrightError) as exc:
            RESULT.update(status="failed", error=str(exc).splitlines()[0][:300])
            log.error("FAILED: %s", exc)
            code = 1
        finally:
            RESULT["final_url"] = page.url if not page.is_closed() else None
            (OUT_DIR / "result.json").write_text(json.dumps(RESULT, indent=2, ensure_ascii=False), encoding="utf-8")
            context.close()
            browser.close()
    print(json.dumps({k: RESULT.get(k) for k in ("status", "data", "payment_reached", "payment_submitted", "blocker", "error")}, indent=2))
    return code


if __name__ == "__main__":
    sys.exit(main())
